// Every unit's action frames and attack type (a port of tools/rom/actions.py):
//   assets/units/act/<gfx>-<type>.png   9 x 4 cells of 32 px: row 0 the attack (down, up, left; 3 frames each), row 1 the
//                                       attack's extra piece, row 2 hurt / guard / cast, row 3 row 2 in the hit flash
//   data/actions.js                     window.ACTIONS = { sheets, heroes, battles }
// The action blobs follow each 0x1200-byte walk sheet: 13 offsets, then RLE data [the loader at 0x0F2D4]; the attack type is
// the unit record's byte +0x2B, which picks the record at 0xE714 + 128 * type + 32 * facing [0x0F2DC].
import { image, cramRGB } from './png.js';

export const HOOKED = [0x06802a];   // units a battle's hook copies in from a record of their own (文王, battles 6 and 7)
export const LEGACY = new Set([0x04f0fc, 0x05219c, 0x054da8, 0x0581c4, 0x05b120, 0x05e3a8, 0x061a72, 0x0c7c6a, 0x0c550c, 0x0b62ba]);   // src/sprites.js: their act_ sheets were the 磻溪 build's

function rle(R, a) {
  const out = [];
  while (R.B(a) !== 0xFF) { const b = R.B(a); if (b > 0xDF) { for (let k = 0; k < b - 0xDF; k++) out.push(R.B(a + 1)); a += 2; } else { out.push(b); a++; } }
  return out;
}
const tiles = buf => { const n = Math.floor(buf.length / 32), out = []; for (let t = 0; t < n; t++) { const px = new Uint8Array(64); for (let i = 0; i < 32; i++) { px[i * 2] = buf[t * 32 + i] >> 4; px[i * 2 + 1] = buf[t * 32 + i] & 15; } out.push(px); } return out; };
function blobs(R, sheet) { const base = sheet + 0x1200; return Array.from({ length: 13 }, (_, k) => tiles(rle(R, base + 0x1A + R.W(base + 2 * k)))); }
// w x h tiles, column-major, drawn into img at (ox, oy) with a palette; tiles past the blob's end stay blank
const ZERO = new Uint8Array(64);
function sprite(img, tl, w, h, start, ox, oy, pal) {
  for (let cx = 0; cx < w; cx++) for (let cy = 0; cy < h; cy++) {
    const t = tl[start + cx * h + cy] || ZERO;   // (a blank tile still writes colour 0 under alpha 0, as the Python did)
    for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) {
      const p = t[y * 8 + x], o = ((oy + cy * 8 + y) * img.w + ox + cx * 8 + x) * 4;
      img.px[o] = pal[p][0]; img.px[o + 1] = pal[p][1]; img.px[o + 2] = pal[p][2]; img.px[o + 3] = p ? 255 : 0;
    }
  }
}
export function actSheet(R, gfx, typ) {
  const RGB = Array.from({ length: 16 }, (_, i) => cramRGB(R.W(0x38436 + 2 * i)));
  const FLASH = RGB.map(c => c.every(v => v === 0) ? [252, 252, 252] : c.map(v => Math.min(252, v + 144)));
  const ATTACK = [0, 1, 2].map(t => [0, 1, 2].map(f => R.sW(0xE714 + t * 128 + f * 32) >> 1));
  const B = blobs(R, gfx), img = image(9 * 32, 128, 4);
  for (let di = 0; di < 3; di++) {
    const tl = B[ATTACK[typ][di]];
    for (let k = 0; k < 3; k++) {
      sprite(img, tl, 4, 4, k * 16, (di * 3 + k) * 32, 0, RGB);
      if (typ !== 2) { const [w, h] = typ === 1 && di < 2 ? [4, 2] : [2, 4]; sprite(img, tl, w, h, 48 + k * 8, (di * 3 + k) * 32, 32, RGB); }
    }
  }
  [6, 7, 8, 3, 4, 5].forEach((b, k) => {
    if (B[b].length < 16) b = ({ 8: 5, 5: 8 })[b] ?? 6;   // a few sheets have a truncated pose blob
    sprite(img, B[b], 4, 4, 0, k * 32, 64, RGB); sprite(img, B[b], 4, 4, 0, k * 32, 96, FLASH);
  });
  if (B[10].length >= 48) for (let k = 0; k < 3; k++) { sprite(img, B[10], 4, 4, k * 16, (6 + k) * 32, 64, RGB); sprite(img, B[10], 4, 4, k * 16, (6 + k) * 32, 96, FLASH); }
  return img;
}
// common: COMMON (heroes with template), battles: { n: extractBattle result (enemies with template) }
export function run(R, files, common, battles, { legacy = false } = {}) {
  const heroes = {}; for (const h of common.heroes) heroes[h.cid] = R.B(h.template + 0x2b);
  const bt = {}; for (let n = 1; n <= 32; n++) bt[n] = battles[n].enemies.map(e => R.B(e.template + 0x2b));
  const sheets = new Map(), add = (g, t) => { if (!sheets.has(g)) sheets.set(g, new Set()); sheets.get(g).add(t); };
  for (const h of common.heroes) add(h.gfx, heroes[h.cid]);
  for (let n = 1; n <= 32; n++) battles[n].enemies.forEach((e, i) => add(e.gfx, bt[n][i]));
  for (let n = 1; n <= 32; n++) for (const r of battles[n].rooms || []) for (const e of r.enemies) add(e.gfx, R.B(e.template + 0x2b));   // the rooms' (battles 10, 11)
  for (const rec of HOOKED) add(R.L(rec + 6), R.B(rec + 0x2b));
  const keep = g => legacy || !LEGACY.has(g), sorted = [...sheets.keys()].sort((a, b) => a - b);
  for (const g of sorted) if (keep(g)) for (const t of sheets.get(g)) if (t <= 2) files['assets/units/act/' + g.toString(16).padStart(6, '0') + '-' + t + '.png'] = actSheet(R, g, t);
  const out = { sheets: Object.fromEntries(sorted.filter(keep).map(g => [g.toString(16).padStart(6, '0'), [...sheets.get(g)].filter(t => t <= 2).sort((a, b) => a - b)])), heroes, battles: bt };
  files['data/actions.js'] = '// generated by the extractor from the player\'s ROM: the attack type (unit record +0x2B: 0 a piece 2x4, 1 a piece 4x2\n// down and up, 2 a bow) of every hero and every battle unit, and the types each graphic is seen with.\nwindow.ACTIONS = ' + JSON.stringify(out) + ';\n';
  return out;
}
