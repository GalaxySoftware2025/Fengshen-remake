// The game's own prompts the remake shows in its menus: data/ui.js, window.UI_TEXT = { key: text }, decoded from the
// glyph strings at their ROM addresses (the camp's, as its menu code at 0x17706 / 0x17768 shows them).
import { s } from './text.js';

const STRINGS = { sortie: 0x13b3c, pick: 0x13b32 };   // 出擊's confirmation; 選擇人物 left empty
export function run(R, files) {
  const out = Object.fromEntries(Object.entries(STRINGS).map(([k, a]) => [k, s(R, a)[0]]));
  files['data/ui.js'] = '// the game\'s prompts: generated by the extractor from the player\'s ROM.\nwindow.UI_TEXT = ' + JSON.stringify(out) + ';\n';
  return out;
}
