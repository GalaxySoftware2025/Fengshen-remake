// The extractor: everything the remake loads that comes from the cartridge, made from the player's own ROM, in the
// browser (a worker; extract/worker.js) or in Node (test/extract-golden.mjs). Nothing of the ROM is shipped with the
// game: the player's copy is read once and the results are kept in the browser (Cache Storage, served by sw.js).
//   extractAll(rom, { part, sounds, log }) -> { path: Uint8Array }
//   part 'data': every image and data file (about a minute); part 'sound': the songs and effects listed in sounds
//   (the logs ripped by running the game's sound driver: about 25 s a song; split over workers)
import { Rom } from './rom.js';
import { MD } from './md.js';
import { encodePNG } from './png.js';
import * as battles from './battles.js';
import * as actions from './actions.js';
import * as items from './items.js';
import * as title from './title.js';
import * as natives from './natives.js';
import * as scenes from './scenes.js';
import * as spellfx from './spellfx.js';
import * as legacy from './legacy.js';
import * as says from './says.js';
import * as ui from './ui.js';
import * as hd from './hd.js';
import * as sound from './sound.js';
import { bootState, record } from './record.js';

// the cartridge this was made from: 2 MB, this SHA-256 (another dump or revision would decode to other tables)
export const ROM_SIZE = 0x200000, ROM_SHA256 = '870e1e55b356d76adf95c50dcafc52021572293224ab537217f9842ccba2fc85';
export async function checkRom(bytes) {
  if (bytes.length !== ROM_SIZE) return 'size ' + bytes.length + ' bytes, not ' + ROM_SIZE;
  const h = [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(v => v.toString(16).padStart(2, '0')).join('');
  return h === ROM_SHA256 ? null : 'SHA-256 ' + h;
}
export const SCENES = ['prologue', 'prologue2', ...Array.from({ length: 65 }, (_, i) => String(i).padStart(2, '0'))];

// the images and data
export function extractData(rom, log = () => {}) {
  const R = new Rom(rom), files = {};
  const base = battles.run(R, rom, files, log); log('battles');
  actions.run(R, files, base.common, base.battles); log('actions');
  items.run(R, rom, files); title.run(R, rom, files); log('items, title');
  const snap = bootState(MD, rom);
  const nat = natives.run(R, rom, files, snap); log('native cuts');
  const recs = {};
  for (const t of SCENES) { recs[t] = record(R, new MD(rom).restore(snap), /^\d+$/.test(t) ? +t : t); log('scene ' + t); }
  scenes.exportScenes(R, rom, recs, base.battles, nat, files, base.sheets); log('scenes');
  for (const g of base.sheets) files['assets/units/' + g.toString(16).padStart(6, '0') + '.png'] = battles.sheetImage(R, g);
  spellfx.run(R, rom, files, snap); log('spell sprites');
  const act = actions.run(R, {}, base.common, base.battles, { legacy: true });
  legacy.run(R, files, { actions: { ...act, common: base.common }, b13: base.battles[13] }); log('legacy sheets');
  says.run(R, files, base.walk, base.battles); ui.run(R, files);
  hd.run(files); log('HD sheets');
  for (const k of Object.keys(files)) if (k.startsWith('research/')) delete files[k];   // (the native cuts' measurements: inputs, not files the game loads)
  return files;
}
// files -> bytes: images to PNG, text to UTF-8
export async function toBytes(files) {
  const out = {}, enc = new TextEncoder();
  for (const [k, v] of Object.entries(files)) {
    if (typeof v === 'string') out[k] = enc.encode(v);
    else if (v instanceof Uint8Array) out[k] = v;
    else out[k] = await encodePNG(v.w, v.h, v.px, v.channels);
  }
  return out;
}
export async function extractAll(rom, { part = 'data', sounds = sound.IDS, log = () => {} } = {}) {
  const bad = await checkRom(rom); if (bad) throw new Error('not the expected ROM: ' + bad);
  if (part === 'sound') {
    const files = {}, snap = bootState(MD, rom), table = {};
    for (const id of sounds) { const r = sound.rip(rom, snap, id), k = sound.nameOf(id); files['assets/audio/' + k + '.vgz'] = await gzip(r.vgm); table[k] = [r.sec, r.loop]; log('sound ' + k); }
    return { files: await toBytes(files), table };
  }
  return { files: await toBytes(extractData(rom, log)) };
}
async function gzip(bytes) { return new Uint8Array(await new Response(new Blob([bytes]).stream().pipeThrough(new CompressionStream('gzip'))).arrayBuffer()); }
// data/audio.js from the sound parts' tables
export function audioTable(tables) {
  const all = Object.assign({}, ...tables), sorted = Object.fromEntries(Object.keys(all).sort().map(k => [k, all[k]]));
  return new TextEncoder().encode('// every song and effect of the original, its length and loop start (seconds): generated by the extractor from the player\'s ROM.\nwindow.AUDIO = ' + JSON.stringify(sorted) + ';\nwindow.AUDIO_LOGS = true;   // (the sounds are logs to synthesize: src/audio.js)\n');
}
